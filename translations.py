DEFAULT_LANGUAGE = "en"


def detect_system_language() -> str:
    """Return the system language code if supported, else English.

    Uses the Windows UI language API first (returns codes like 'ru'),
    falls back to locale parsing for non-Windows environments.

    Returns:
        Language code from LANG_DISPLAY_NAMES.
    """
    code = ""
    try:
        import ctypes
        langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        code = locale.windows_locale.get(langid, "").split("_")[0]
    except (AttributeError, OSError, ImportError):
        pass
    if not code:
        try:
            system_lang = (locale.getlocale()[0] or "").lower()
            code = system_lang.split("_")[0]
            if code not in LANG_DISPLAY_NAMES:
                for known in LANG_DISPLAY_NAMES:
                    if system_lang.startswith(known):
                        code = known
                        break
        except (ValueError, TypeError):
            code = ""
    return code if code in LANG_DISPLAY_NAMES else DEFAULT_LANGUAGE


def t(language: str, key: str) -> str:
    """Translate a key for the given language with English fallback.

    Args:
        language: Language code.
        key: Translation key.

    Returns:
        Translated string, or the key itself if missing everywhere.
    """
    return TRANSLATIONS.get(language, TRANSLATIONS[DEFAULT_LANGUAGE]).get(
        key, TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    )

